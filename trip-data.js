function parseCSV(text) {
  const rows = []; let row = [], f = "", q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) { if (c === '"') { if (text[i + 1] === '"') { f += '"'; i++; } else q = false; } else f += c; }
    else if (c === '"') q = true;
    else if (c === ",") { row.push(f); f = ""; }
    else if (c === "\n" || c === "\r") { if (c === "\r" && text[i + 1] === "\n") i++; row.push(f); rows.push(row); row = []; f = ""; }
    else f += c;
  }
  if (f || row.length) { row.push(f); rows.push(row); }
  return rows;
}

function buildTrip(rows) {
  const head = rows[0].map(h => h.trim());
  const col = name => head.indexOf(name);
  const cDay = col("วัน"), cTime = col("เวลา"), cText = col("กิจกรรม"), cType = col("ประเภท"), cMap = col("ค้นหาในแผนที่"), cTitle = col("หัวข้อวัน");
  if (cDay < 0 || cTime < 0 || cText < 0) throw new Error("หัวตารางไม่ตรง");
  const days = {}, titles = {};
  for (const r of rows.slice(1)) {
    const n = parseInt(r[cDay], 10), text = (r[cText] || "").trim();
    if (!n || !text) continue;
    const time = (r[cTime] || "").trim().replace(/(\d{1,2}:\d{2}):\d{2}/g, "$1").replace(/(\d)\.(\d{2})/g, "$1:$2").replace(/\s*[-–]\s*/, "–");
    const type = TYPE_FROM_TH[(r[cType] || "").trim()] || "activity";
    if (cTitle >= 0 && !titles[n] && (r[cTitle] || "").trim()) titles[n] = r[cTitle].trim();
    (days[n] = days[n] || []).push([time, text, type, cMap >= 0 ? (r[cMap] || "").trim() : ""]);
  }
  const nums = Object.keys(days).map(Number).sort((a, b) => a - b);
  if (!nums.length) throw new Error("ไม่มีข้อมูล");
  return nums.map(n => {
    const { date: iso, label } = dayMeta(n - 1);
    const fb = FALLBACK.find(x => x.date === iso);
    const places = days[n].filter(x => x[2] === "place").map(x => x[1]);
    return {
      date: iso,
      label,
      title: titles[n] || (fb ? fb.title : places.slice(0, 3).join(" → ") || `วันที่ ${n}`),
      items: days[n],
    };
  });
}

// คำนวณวันที่แบบไม่ขึ้นกับเขตเวลาของเครื่อง
function dayMeta(n) {
  const d = new Date(Date.UTC(2026, 11, 26 + n));
  return { date: d.toISOString().slice(0, 10), label: `${TH_DAYS[d.getUTCDay()]} ${d.getUTCDate()} ${TH_MONTHS[d.getUTCMonth()]}` };
}

// โหลดแพลนล่าสุดจากชีต (คืนค่า array ของวัน หรือ throw ถ้าโหลดไม่ได้)
async function fetchTrip() {
  const url = `https://docs.google.com/spreadsheets/d/${SHEET_ID}/gviz/tq?tqx=out:csv&headers=1&sheet=${encodeURIComponent(SHEET_TAB)}&t=${Date.now()}`;
  const res = await fetch(url, { cache: "no-store" });
  if (!res.ok) throw new Error("HTTP " + res.status);
  return buildTrip(parseCSV(await res.text()));
}
